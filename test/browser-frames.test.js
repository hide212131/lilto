const test = require("node:test");
const assert = require("node:assert/strict");
const { FrameTracker, isHttpOrigin } = require("../dist/main/browser-frames.js");
const { FakeWebContents } = require("./helpers/browser-fakes.js");

const CTX = { viewEpoch: 1, ownershipEpoch: 1, documentEpoch: 1 };

function tree() {
  const wc = new FakeWebContents();
  wc.mainFrame.url = "https://top.example/";
  const a = wc.addFrame({ url: "https://a.example/x", name: "dup", processId: 2 });
  const b = wc.addFrame({ url: "https://a.example/x", name: "dup", processId: 2 }); // same name, same URL
  const blank = wc.addFrame({ url: "about:blank", origin: "https://top.example", name: "blank" }); // inherited origin
  const srcdoc = wc.addFrame({ url: "about:srcdoc", origin: "https://top.example", name: "srcdoc" });
  const opaque = wc.addFrame({ url: "https://a.example/s", origin: "null", name: "sandboxed" });
  const data = wc.addFrame({ url: "data:text/html,x", origin: "null", name: "data" });
  const file = wc.addFrame({ url: "file:///x", origin: "file://", name: "file" });
  const nested = wc.addFrame({ url: "https://c.example/", parent: a, name: "nested", processId: 3 });
  const tracker = new FrameTracker();
  const nav = (frame) => wc.on("did-start-navigation", (details) => tracker.onNavigation(wc.mainFrame, details.frame));
  nav();
  wc.on("did-frame-navigate", (...args) => tracker.onNavigation(wc.mainFrame, null, { processId: args[5], routingId: args[6] }));
  wc.on("did-navigate-in-page", (...args) => tracker.onNavigation(wc.mainFrame, null, { processId: args[3], routingId: args[4] }));
  return { wc, tracker, a, b, blank, srcdoc, opaque, data, file, nested };
}

test("isHttpOrigin: only real http(s) origins; opaque 'null', file and empty are not evaluable", () => {
  assert.equal(isHttpOrigin("https://a.example"), true);
  assert.equal(isHttpOrigin("http://127.0.0.1:3000"), true);
  for (const bad of ["null", "", "file://", "about:blank", "data:", "blob:https://a.example/x", "chrome://x"]) assert.equal(isHttpOrigin(bad), false, bad);
});

test("frame list is generated by Main: parents, evaluable flags and reasons come from frame.origin, not from the page", () => {
  const { wc, tracker } = tree();
  const { frames, truncated } = tracker.list(wc.mainFrame, CTX);
  assert.equal(truncated, false);
  const byName = Object.fromEntries(frames.map((f) => [f.name || "(main)", f]));
  assert.equal(byName["(main)"].isMainFrame, true);
  assert.equal(byName["(main)"].parentFrameId, null);
  assert.equal(byName.nested.parentFrameId, frames.find((f) => f.url === "https://a.example/x").frameId);
  for (const ok of ["(main)", "blank", "srcdoc", "nested"]) assert.equal(byName[ok].evaluable, true, ok);
  assert.equal(byName.blank.origin, "https://top.example", "inherited origin is reported");
  for (const no of ["sandboxed", "data", "file"]) assert.equal(byName[no].evaluable, false, no);
  assert.equal(byName.sandboxed.unsupportedReason, "opaque origin");
  assert.equal(byName.file.unsupportedReason, "non-http(s) origin");
  assert.equal(new Set(frames.map((f) => f.frameId)).size, frames.length, "unique opaque ids");
  assert.ok(frames.every((f) => /^f[\w-]+$/.test(f.frameId) && f.frameId.length <= 128));
});

test("same name + same URL frames get distinct ids, each resolving to its own frame (no lookup by name/URL)", () => {
  const { wc, tracker, a, b } = tree();
  const { frames } = tracker.list(wc.mainFrame, CTX);
  const dups = frames.filter((f) => f.name === "dup");
  assert.equal(dups.length, 2);
  assert.equal(tracker.resolve(dups[0].frameId, wc.mainFrame, CTX).frame, a);
  assert.equal(tracker.resolve(dups[1].frameId, wc.mainFrame, CTX).frame, b);
});

test("a frame navigation (start, commit or reload of the same URL) invalidates ids bound to the older document", () => {
  const { wc, tracker, a } = tree();
  let { frames } = tracker.list(wc.mainFrame, CTX);
  const id = frames.find((f) => f.url === "https://a.example/x" && f.name === "dup").frameId;
  assert.equal(tracker.resolve(id, wc.mainFrame, CTX).frame, a);
  a.navigate("https://a.example/x"); // reload: SAME url, new document
  assert.throws(() => tracker.resolve(id, wc.mainFrame, CTX), { code: "STALE_FRAME", effect: "none" });
  // a fresh listing resolves again
  frames = tracker.list(wc.mainFrame, CTX).frames;
  const fresh = frames.find((f) => f.name === "dup" && f.frameId !== id).frameId;
  assert.ok(tracker.resolve(fresh, wc.mainFrame, CTX));
  // navigation START alone (not committed yet) also invalidates
  wc.emit("did-start-navigation", { frame: a, isMainFrame: false, isSameDocument: false });
  assert.throws(() => tracker.resolve(fresh, wc.mainFrame, CTX), { code: "STALE_FRAME" });
});

test("SPA (in-page) navigation of a frame invalidates its id; other frames' ids survive", () => {
  const { wc, tracker, a, b } = tree();
  const { frames } = tracker.list(wc.mainFrame, CTX);
  const [ida, idb] = frames.filter((f) => f.name === "dup").map((f) => f.frameId);
  wc.emit("did-navigate-in-page", {}, "https://a.example/x#y", false, a.processId, a.routingId);
  assert.throws(() => tracker.resolve(ida, wc.mainFrame, CTX), { code: "STALE_FRAME" });
  assert.equal(tracker.resolve(idb, wc.mainFrame, CTX).frame, b);
});

test("removed / detached frames and a replaced process or routing id are STALE_FRAME", () => {
  const { wc, tracker, a, b } = tree();
  const { frames } = tracker.list(wc.mainFrame, CTX);
  const [ida, idb] = frames.filter((f) => f.name === "dup").map((f) => f.frameId);
  a.detached = true;
  assert.throws(() => tracker.resolve(ida, wc.mainFrame, CTX), { code: "STALE_FRAME" });
  wc.frameList.splice(wc.frameList.indexOf(b), 1);
  assert.throws(() => tracker.resolve(idb, wc.mainFrame, CTX), { code: "STALE_FRAME" });
  const t2 = tree();
  const f2 = t2.tracker.list(t2.wc.mainFrame, CTX).frames.find((f) => f.name === "dup");
  t2.a.routingId += 5; // replaced without us seeing an event
  assert.throws(() => t2.tracker.resolve(f2.frameId, t2.wc.mainFrame, CTX), { code: "STALE_FRAME" });
});

test("ids are bound to view, ownership and top document epochs", () => {
  const { wc, tracker } = tree();
  const id = tracker.list(wc.mainFrame, CTX).frames[1].frameId;
  for (const key of ["viewEpoch", "ownershipEpoch", "documentEpoch"]) {
    assert.throws(() => tracker.resolve(id, wc.mainFrame, { ...CTX, [key]: CTX[key] + 1 }), { code: "STALE_FRAME" }, key);
  }
  assert.ok(tracker.resolve(id, wc.mainFrame, CTX));
});

test("another view's frame ids (and unknown/guessed ids) never resolve", () => {
  const one = tree();
  const two = tree();
  const idFromOne = one.tracker.list(one.wc.mainFrame, CTX).frames[1].frameId;
  assert.throws(() => two.tracker.resolve(idFromOne, two.wc.mainFrame, CTX), { code: "STALE_FRAME" });
  // even given the matching tracker, a frame that is not in THIS root's subtree is refused
  assert.throws(() => one.tracker.resolve(idFromOne, two.wc.mainFrame, CTX), { code: "STALE_FRAME" });
  for (const guess of ["", "f1", "main", "https://a.example/x", "dup"]) assert.throws(() => one.tracker.resolve(guess, one.wc.mainFrame, CTX), { code: "STALE_FRAME" });
});

test("ids expire after 60 seconds", () => {
  let clock = 1_000;
  const { wc } = tree();
  const tracker = new FrameTracker(() => clock);
  const id = tracker.list(wc.mainFrame, CTX).frames[0].frameId;
  clock += 59_000;
  assert.ok(tracker.resolve(id, wc.mainFrame, CTX));
  clock += 2_000;
  assert.throws(() => tracker.resolve(id, wc.mainFrame, CTX), { code: "STALE_FRAME" });
});

test("a frame that became opaque/non-http(s) after listing is UNSUPPORTED_TARGET, not evaluated", () => {
  const { wc, tracker, blank } = tree();
  const id = tracker.list(wc.mainFrame, CTX).frames.find((f) => f.name === "blank").frameId;
  blank.explicitOrigin = "null";
  assert.throws(() => tracker.resolve(id, wc.mainFrame, CTX), { code: "UNSUPPORTED_TARGET", effect: "none" });
});

test("list is bounded: at most 128 frames and 64 KiB, with truncated=true and long URLs/names clipped", () => {
  const wc = new FakeWebContents();
  wc.mainFrame.url = "https://top.example/";
  for (let i = 0; i < 200; i += 1) wc.addFrame({ url: `https://a.example/${i}`, name: `n${i}` });
  const tracker = new FrameTracker();
  const big = tracker.list(wc.mainFrame, CTX);
  assert.equal(big.frames.length, 128);
  assert.equal(big.truncated, true);
  const wc2 = new FakeWebContents();
  wc2.mainFrame.url = "https://top.example/";
  for (let i = 0; i < 100; i += 1) wc2.addFrame({ url: `https://a.example/${"p".repeat(5000)}`, name: "n".repeat(500) });
  const heavy = new FrameTracker().list(wc2.mainFrame, CTX);
  assert.ok(Buffer.byteLength(JSON.stringify(heavy.frames)) <= 64 * 1024);
  assert.ok(heavy.frames.every((f) => f.url.length <= 2049 && f.name.length <= 129));
  assert.equal(heavy.truncated, heavy.frames.length < 101);
});
